//Create a program to convert the distance of 10.8 kilometers to miles.


public class KmToMiles {
    public static void main(String[] args){

        //storing the distance in kilometers
        double kilo = 10.8;

        //converting the distance in miles
        double miles = kilo * 1.6;

        //displaying the required output
        System.out.println("The distance " + kilo +" km in miles is " + miles);
    }
}
